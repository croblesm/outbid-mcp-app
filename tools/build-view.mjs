// Bundles mcp-view/ and writes it into the Edge Function as a string module, so deploy needs no build step.
// Run: npm run build:view (commit the generated supabase/functions/mcp/tools/view.ts).
import { execSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"

execSync("npx vite build --config vite.view.config.ts --logLevel warn", { stdio: "inherit" })
const html = readFileSync("dist-view/index.html", "utf8")
if (!html.includes("<script")) throw new Error("view build has no inline script")
writeFileSync(
  "supabase/functions/mcp/tools/view.ts",
  `// Generated by tools/build-view.mjs from mcp-view/. Do not edit.\nexport const VIEW_HTML = ${JSON.stringify(html)}\n`,
)
console.log(`supabase/functions/mcp/tools/view.ts: ${(html.length / 1024).toFixed(0)} KiB`)
