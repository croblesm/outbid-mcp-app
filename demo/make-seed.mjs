// Writes demo/seed.sql from src/lots.json, the one catalog the mock and the database share.
// Run after editing the lots: node demo/make-seed.mjs && cp demo/seed.sql supabase/seed.sql
import { readFileSync, writeFileSync } from "node:fs"

const lots = JSON.parse(readFileSync(new URL("../src/lots.json", import.meta.url), "utf8"))
const q = (s) => `'${s.replaceAll("'", "''")}'`
const rows = lots.map((l) => `  (${[q(l.title), q(l.description), l.starting_price, l.increment].join(", ")})`)

writeFileSync(
  new URL("./seed.sql", import.meta.url),
  `-- supabase/seed.sql: runs on \`supabase db reset\` after migrations. Generated by demo/make-seed.mjs from src/lots.json.
-- Lot photos bucket (pg-delta does not diff bucket rows, so it lives here).
insert into storage.buckets (id, name, public)
values ('lots', 'lots', true)
on conflict (id) do nothing;

insert into public.lots (title, description, starting_price, increment) values
${rows.join(",\n")};
`,
)
console.log(`demo/seed.sql: ${lots.length} lots`)
